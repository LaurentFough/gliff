pub fn evdev(mac: u16) -> Option<u32> {
    KEYS.iter().find(|(m, _)| *m == mac).map(|(_, e)| *e)
}

pub fn mac(evdev: u32) -> Option<u16> {
    KEYS.iter().find(|(_, e)| *e == evdev).map(|(m, _)| *m)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn positions_roundtrip_without_collisions() {
        for &(m, e) in KEYS {
            assert_eq!(evdev(m), Some(e));
            assert_eq!(mac(e), Some(m));
        }
        assert_eq!(evdev(0), Some(30)); // A
        assert_eq!(evdev(55), Some(125)); // Command → Super
        assert_eq!(mac(28), Some(36)); // Enter
        assert_eq!(evdev(63), None); // Fn has no evdev equivalent
        assert_eq!(mac(u32::MAX), None);
    }
}
